const foldedTranslations = Object.fromEntries(catalog.map((row) => [row[0].toLowerCase(), row]));
export function translate(
  source: string,
  locale: Locale,
  variables: Record<string, string | number> = {},
) {
  const key = source.trim().replace(/\s+/g, " ");
  const resolved = aliases[key] ?? key;
  const index = locales.indexOf(locale);
  const found =
    translations[resolved]?.[index] ?? foldedTranslations[resolved.toLowerCase()]?.[index];
  const value = found
    ? (source.startsWith(" ") ? " " : "") + found + (source.endsWith(" ") ? " " : "")
    : locale === "en" && aliases[key]
      ? resolved
      : source;
  return value.replace(/\{(\w+)\}/g, (match, name) =>
    Object.hasOwn(variables, name) ? String(variables[name]) : match,
  );
}
